            <div id="art_2" class="reglamento_art">
                <h4 class="titulo">ART.1.1 Comportamiento general de los participantes</h4>
                <div class="texto_articulo"> 

                        <p>1.1.1. Todo participante tiene el deber de prestar socorro a otro participante que esté en peligro o accidentado, estando obligado a comunicarlo al control más cercano inmediatamente. La privación de auxilio será penalizada con la descalificación inmediata.</p>
                        <p>1.1.2. Es obligación de cada participante portar consigo cualquier residuo que genere: envases, papeles, residuos orgánicos, etc., hasta los lugares señalados y habilitados por la organización.</p>
                        <p>1.1.3. Todo participante deberá realizar el recorrido marcado y balizado por la organización. No respetarlo o no pasar por alguno de los controles establecidos será causa de descalificación.</p>
                        <p>1.1.4. Los participantes deberán seguir, en todo momento y durante todo el recorrido, las instrucciones de los miembros de la organización.</p>
                        <p>1.1.5. Los participantes deben comportarse deportivamente en todo momento y mostrarse respetuosos con los demás deportistas, comisarios y demás miembros de la organización. Además, deben ser cuidadosos con las instalaciones habilitadas para la prueba.</p>
                        <p>1.1.6. Un participante podrá retirarse de la prueba siempre que él lo desee, pero deberá hacerlo de acuerdo con los puntos siguientes:</p>
                        <ul>
                            <li>Se retirará en un control y entregará el dorsal.</li>
                            <li>El participante asumirá toda responsabilidad desde que abandone voluntariamente la prueba.</li>
                            <li>La organización facilitará la evacuación a la zona de meta de los participantes en la medida de lo  posible respetando el curso de la prueba.</li>
                        </ul>

                 </div>
            </div>
            
